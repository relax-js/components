// Takes the component screenshots the manual shows. Starts the gallery's dev server, captures each
// shot in demos/gallery/src/shots.ts, then rewrites the generated parts of the manual: every
// `<!-- screenshots: r-tag -->` block, and docs/manual/Gallery.md. Images follow the folders of
// src/: the `sorted` shot of r-table, from src/data-display/table/, is
// docs/manual/images/data-display/table/sorted.png.
//
// The manual ships in the package but the images do not, so the manual links them on GitHub. A new
// or changed image shows in the manual once it is pushed to the main branch.
//
//   npm run docs:screenshots                       every shot
//   npm run docs:screenshots -- r-table            every shot of r-table
//   npm run docs:screenshots -- r-table/sorted     one shot
import { fileURLToPath } from 'node:url';
import { mkdir, readdir, readFile, rm, writeFile } from 'node:fs/promises';
import { dirname, join, relative } from 'node:path';
import { chromium } from 'playwright';
import { createServer } from 'vite';

const galleryFolder = fileURLToPath(new URL('./', import.meta.url));
const manualFolder = fileURLToPath(new URL('../../docs/manual/', import.meta.url));
const sourceFolder = fileURLToPath(new URL('../../src/', import.meta.url));
const imagesFolder = join(manualFolder, 'images');
const galleryPage = join(manualFolder, 'Gallery.md');
const filters = process.argv.slice(2);
const imagesUrl = await publishedImagesUrl();

const generatedNote = '<!-- Generated by `npm run docs:screenshots` from demos/gallery/src/shots.ts; edits here are overwritten. -->';
const blockPattern = /(<!-- screenshots: ([a-z0-9-]+) -->\r?\n)[\s\S]*?(<!-- \/screenshots -->)/g;

const server = await createServer({ root: galleryFolder, configFile: join(galleryFolder, 'vite.config.ts'), logLevel: 'error' });
await server.listen();
const baseUrl = server.resolvedUrls.local[0];
const browser = await chromium.launch();
let failures = 0;
let shots;
try {
    const context = await browser.newContext({ colorScheme: 'light', locale: 'en-GB', reducedMotion: 'reduce', deviceScaleFactor: 1 });
    shots = await listShots(context);
    await placeInSourceFolders(shots);
    const chosen = filters.length === 0 ? shots : shots.filter((shot) => filters.some((filter) => idOf(shot) === filter || shot.tag === filter));
    if (chosen.length === 0) {
        throw new Error(`No shot is named ${filters.join(' or ')}; use a tag or tag/state`);
    }

    for (const shot of chosen) {
        failures += (await capture(context, shot)) ? 0 : 1;
    }
    if (filters.length === 0) {
        await removeStaleImages(shots);
    }
} finally {
    await browser.close();
    await server.close();
}

const pages = await fillManualPages(shots);
await writeFile(galleryPage, galleryMarkdown(shots, pages));
console.log(`updated ${relative(process.cwd(), galleryPage)}`);
for (const tag of new Set(shots.map((shot) => shot.tag))) {
    if (!pages.has(tag)) {
        console.log(`note: no manual page has a "<!-- screenshots: ${tag} -->" block; its images are only in Gallery.md`);
    }
}
if (failures > 0) {
    console.error(`${failures} shot(s) failed`);
    process.exitCode = 1;
}

function idOf(shot) {
    return `${shot.tag}/${shot.name}`;
}

/** Where a shot's image goes, relative to the images folder: the component's folder in src/, then the state. */
function imageOf(shot) {
    return `${shot.folder}/${shot.name}.png`;
}

/** Gives each shot `folder`, its component's folder under src/, such as `data-display/table` for r-table. */
async function placeInSourceFolders(shots) {
    const folders = new Map();
    for (const category of await readdir(sourceFolder, { withFileTypes: true })) {
        if (category.isDirectory()) {
            for (const component of await readdir(join(sourceFolder, category.name), { withFileTypes: true })) {
                if (component.isDirectory()) {
                    folders.set(`r-${component.name}`, `${category.name}/${component.name}`);
                }
            }
        }
    }
    for (const shot of shots) {
        shot.folder = folders.get(shot.tag);
        if (!shot.folder) {
            throw new Error(`${idOf(shot)}: no folder src/*/${shot.tag.replace(/^r-/, '')}/ for ${shot.tag}`);
        }
    }
}

async function listShots(context) {
    const page = await context.newPage();
    await page.goto(`${baseUrl}?list`);
    await page.waitForFunction(() => window.gallery !== undefined);
    const list = await page.evaluate(() => window.gallery.shots);
    await page.close();
    return list;
}

/** Captures one shot on a page of its own, so no state carries over. Returns whether it worked. */
async function capture(context, shot) {
    const page = await context.newPage();
    const errors = [];
    page.on('pageerror', (error) => errors.push(error.message));
    try {
        if (shot.window) {
            await page.setViewportSize({ width: shot.width ?? 720, height: shot.height ?? 480 });
        }
        await page.goto(`${baseUrl}?shot=${idOf(shot)}`);
        await page.waitForSelector('body[data-ready]', { timeout: 10_000 });
        // lets transitions and fonts settle; motion is reduced, so this is short
        await page.waitForTimeout(150);
        if (errors.length > 0) {
            throw new Error(errors.join('\n'));
        }
        const path = join(imagesFolder, imageOf(shot));
        await mkdir(dirname(path), { recursive: true });
        if (shot.window) {
            await page.screenshot({ path });
        } else {
            await page.locator('.stage').screenshot({ path });
        }
        console.log(`saved ${relative(process.cwd(), path)}`);
        return true;
    } catch (error) {
        console.error(`${idOf(shot)}: ${error.message}`);
        return false;
    } finally {
        await page.close();
    }
}

/** Removes the images of shots that no longer exist, and the folders that leaves empty. */
async function removeStaleImages(shots) {
    const wanted = new Set(shots.map((shot) => join(imagesFolder, imageOf(shot))));
    const entries = await readdir(imagesFolder, { withFileTypes: true, recursive: true });
    for (const entry of entries.filter((candidate) => candidate.isFile())) {
        const path = join(entry.parentPath, entry.name);
        if (!wanted.has(path)) {
            await rm(path);
            console.log(`removed ${relative(process.cwd(), path)}, its shot is gone`);
        }
    }
    // deepest first, so a category empties after its components
    const folders = entries.filter((entry) => entry.isDirectory()).map((entry) => join(entry.parentPath, entry.name));
    for (const folder of folders.sort((a, b) => b.length - a.length)) {
        if ((await readdir(folder)).length === 0) {
            await rm(folder, { recursive: true });
        }
    }
}

async function markdownFiles(folder) {
    const entries = await readdir(folder, { withFileTypes: true, recursive: true });
    return entries
        .filter((entry) => entry.isFile() && entry.name.endsWith('.md'))
        .map((entry) => join(entry.parentPath, entry.name))
        .filter((file) => file !== galleryPage);
}

/** Where the images are served on GitHub, from the repository in package.json. */
async function publishedImagesUrl() {
    const packageJson = JSON.parse(await readFile(new URL('../../package.json', import.meta.url), 'utf8'));
    const repository = /github\.com\/([^/]+\/[^/.]+)/.exec(packageJson.repository?.url ?? '')?.[1];
    if (!repository) {
        throw new Error('package.json has no GitHub repository to link the images from');
    }
    return `https://raw.githubusercontent.com/${repository}/main/docs/manual/images/`;
}

function imagesMarkdown(shots) {
    return shots.map((shot) => `**${shot.title}**\n\n![${shot.title}](${imagesUrl}${imageOf(shot)})\n`).join('\n');
}

/** Rewrites every screenshots block in the manual. Returns the page each tag's block is on. */
async function fillManualPages(shots) {
    const pages = new Map();
    for (const file of await markdownFiles(manualFolder)) {
        const original = await readFile(file, 'utf8');
        const updated = original.replaceAll(blockPattern, (_, start, tag, end) => {
            const own = shots.filter((shot) => shot.tag === tag);
            if (own.length === 0) {
                console.error(`${relative(process.cwd(), file)}: no shot shows ${tag}`);
                process.exitCode = 1;
            }
            pages.set(tag, file);
            const block = `${generatedNote}\n\n${imagesMarkdown(own)}\n`;
            // keeps the page's own line endings
            return `${start}${start.endsWith('\r\n') ? block.replaceAll('\n', '\r\n') : block}${end}`;
        });
        if (updated !== original) {
            await writeFile(file, updated);
            console.log(`updated ${relative(process.cwd(), file)}`);
        }
    }
    return pages;
}

function galleryMarkdown(shots, pages) {
    const sections = [];
    for (const tag of new Set(shots.map((shot) => shot.tag))) {
        const own = shots.filter((shot) => shot.tag === tag);
        const page = pages.get(tag);
        const link = page ? ` · [manual](${relative(manualFolder, page).replaceAll('\\', '/')})` : '';
        sections.push(`## \`<${tag}>\`${link}\n\n${imagesMarkdown(own)}`);
    }
    return [
        '# Gallery',
        '',
        generatedNote,
        '',
        'Every component in the states the screenshot script captures, in the light theme. `npm run demo:gallery` shows the same states live (port 5304).',
        '',
        sections.join('\n'),
    ].join('\n');
}
